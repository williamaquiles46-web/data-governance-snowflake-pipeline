USE DATABASE GOVERNANCA_CORP;

SELECT 
    CATEGORIA_PRODUTO,
    ROUND(SUM(VALOR_BRUTO), 2) AS FATURAMENTO_TOTAL
FROM TRUSTED_DATA.FATO_TRANSACAO_PADRONIZADA
GROUP BY CATEGORIA_PRODUTO
ORDER BY FATURAMENTO_TOTAL DESC;

SELECT 
    SISTEMA_ORIGEM,
    MOTIVO_REJEICAO,
    COUNT(*) AS TOTAL_ERROS
FROM DATA_QUALITY_METRICS.LOG_ANOMALIAS_DADOS
GROUP BY SISTEMA_ORIGEM, MOTIVO_REJEICAO
ORDER BY TOTAL_ERROS DESC;

SELECT 
    DATE(DATA_REGISTRO) AS DIA_TRANSACAO,
    ROUND(SUM(VALOR_BRUTO), 2) AS RECEITA_DIARIA,
    COUNT(*) AS TOTAL_PEDIDOS
FROM TRUSTED_DATA.FATO_TRANSACAO_PADRONIZADA
GROUP BY DATE(DATA_REGISTRO)
ORDER BY DIA_TRANSACAO ASC;