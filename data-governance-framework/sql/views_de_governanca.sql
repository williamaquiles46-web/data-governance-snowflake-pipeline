USE DATABASE GOVERNANCA_CORP;

CREATE OR REPLACE VIEW DATA_QUALITY_METRICS.VW_RESUMO_GOVERNANCA_DADOS AS
WITH metricas_trusted AS (
    SELECT 
        COUNT(*) AS total_conformes,
        COUNT(DISTINCT ID_TRANSACAO) AS total_transacoes_unicas,
        ROUND(SUM(VALOR_BRUTO), 2) AS valor_financeiro_preservado
    FROM TRUSTED_DATA.FATO_TRANSACAO_PADRONIZADA
),
metricas_quarentena AS (
    SELECT 
        COUNT(*) AS total_quarentena
    FROM DATA_QUALITY_METRICS.LOG_ANOMALIAS_DADOS
)
SELECT 
    t.total_conformes AS REGISTROS_CONFORMES,
    q.total_quarentena AS REGISTROS_REJEITADOS,
    (t.total_conformes + q.total_quarentena) AS TOTAL_PROCESSADO,
    ROUND((t.total_conformes / (t.total_conformes + q.total_quarentena)) * 100, 2) AS TAXA_CONFORMIDADE_PCT,
    ROUND((q.total_quarentena / (t.total_conformes + q.total_quarentena)) * 100, 2) AS TAXA_ERRO_PCT,
    t.valor_financeiro_preservado AS VOLUME_FINANCEIRO_TOTAL
FROM metricas_trusted t, metricas_quarentena q;

CREATE OR REPLACE VIEW DATA_QUALITY_METRICS.VW_ANOMALIAS_POR_ORIGEM AS
SELECT 
    SISTEMA_ORIGEM,
    MOTIVO_REJEICAO,
    COUNT(*) AS TOTAL_OCORRENCIAS,
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (PARTITION BY SISTEMA_ORIGEM), 2) AS PCT_DO_SISTEMA
FROM DATA_QUALITY_METRICS.LOG_ANOMALIAS_DADOS
GROUP BY SISTEMA_ORIGEM, MOTIVO_REJEICAO
ORDER BY SISTEMA_ORIGEM, TOTAL_OCORRENCIAS DESC;

CREATE OR REPLACE VIEW TRUSTED_DATA.VW_METRICAS_VENDAS_CATEGORIA AS
SELECT 
    CATEGORIA_PRODUTO,
    COUNT(ID_TRANSACAO) AS TOTAL_TRANSACOES,
    ROUND(SUM(VALOR_BRUTO), 2) AS RECEITA_TOTAL,
    ROUND(AVG(VALOR_BRUTO), 2) AS TICKET_MEDIO,
    ROUND(MIN(VALOR_BRUTO), 2) AS MENOR_VENDA,
    ROUND(MAX(VALOR_BRUTO), 2) AS MAIOR_VENDA
FROM TRUSTED_DATA.FATO_TRANSACAO_PADRONIZADA
GROUP BY CATEGORIA_PRODUTO
ORDER BY RECEITA_TOTAL DESC;