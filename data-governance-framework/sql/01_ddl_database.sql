CREATE DATABASE IF NOT EXISTS GOVERNANCA_CORP;

USE DATABASE GOVERNANCA_CORP;

CREATE SCHEMA IF NOT EXISTS TRUSTED_DATA;
CREATE IF NOT EXISTS DATA_QUALITY_METRIC;

CREATE OR REPLACE TABLE TRUSTED_DATA.FATO_TRANSACAO_PADRONIZADA (
    ID_TRANSACAO VARCHAR(50) NOT NULL,
    DATA_REGISTRO TIMESTAMP_NTZ NOT NULL,
    SISTEMA_ORIGEM VARCHAR(50) NOT NULL,
    CATEGORIA_PRODUTO VARCHAR(100) NOT NULL,
    VALOR_BRUTO NUMBER(12, 2) NOT NULL,
    DATA_INGESTAO_DWH TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE DATA_QUALITY_METRICS.LOG_ANOMALIAS_DADOS (
    ID_LOG INT,
    SISTEMA_ORIGEM VARCHAR(50) NOT NULL,
    DATA_EVENTO TIMESTAMP_NTZ NOT NULL,
    MOTIVO_REJEICAO VARCHAR(255) NOT NULL,
    DATA_AUDITORIA TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);